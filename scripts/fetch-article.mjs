#!/usr/bin/env node
// Builds a compact preview card for a dev.to article, small enough to sit in a
// timeline card without scrolling. dev.to itself cannot be framed
// (`frame-ancestors https://dev.to`), and reading happens on dev.to, so the
// snapshot only carries cover, title, meta and a link out.
//
// Usage:
//   node scripts/fetch-article.mjs
//   node scripts/fetch-article.mjs <slug-or-id> <output-file>
//
// No dependencies, needs Node 18+ (global fetch).

import { writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const slug = process.argv[2] ?? 'tabnas-how-to-define-a-grammar-243i'
const outFile = resolve(process.argv[3] ?? 'articles/tabnas-preview.html')

const username = 'pablodevrel'
const headers = { 'User-Agent': 'pablodevrel-site', Accept: 'application/json' }

// `/api/articles/{username}/{slug}` is unreliable (it serves cached 404s), so
// resolve the numeric id through the article listing and use that endpoint.
async function getArticle(ref) {
  if (/^\d+$/.test(ref)) {
    const res = await fetch(`https://dev.to/api/articles/${ref}`, { headers })
    if (res.ok) return res.json()
  } else {
    const res = await fetch(`https://dev.to/api/articles/${username}/${ref}`, {
      headers,
    })
    if (res.ok) return res.json()
  }

  const list = await fetch(
    `https://dev.to/api/articles?username=${username}&per_page=100`,
    { headers },
  )
  if (!list.ok) throw new Error(`listing failed: ${list.status}`)
  const match = (await list.json()).find(
    (a) => String(a.id) === ref || a.slug === ref,
  )
  if (!match) throw new Error(`no article found for "${ref}"`)

  const res = await fetch(`https://dev.to/api/articles/${match.id}`, { headers })
  if (!res.ok) throw new Error(`article ${match.id} -> ${res.status}`)
  return res.json()
}

const article = await getArticle(slug)

const esc = (s) =>
  String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')

const published = article.published_at
  ? new Date(article.published_at).toLocaleDateString('en-GB', {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    })
  : ''
const canonical = `https://dev.to/${article.user?.username ?? username}/${article.slug}`
const meta = [
  'dev.to',
  article.reading_time_minutes ? `${article.reading_time_minutes} min read` : '',
  published,
]
  .filter(Boolean)
  .join(' · ')

const html = `<!doctype html>
<!-- Generated by scripts/fetch-article.mjs from ${canonical}
     Regenerate with: node scripts/fetch-article.mjs -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(article.title)}</title>
    <style>
      :root {
        --background: #ffffff;
        --surface-muted: #f6f8fa;
        --text: #24292e;
        --text-muted: #57606a;
        --border: #d0d7de;
        --primary: #f36132;
      }
      @media (prefers-color-scheme: dark) {
        :root {
          --background: #161b22;
          --surface-muted: #111827;
          --text: #d8e3ff;
          --text-muted: #94a3b8;
          --border: #30363d;
          --primary: #ff8b60;
        }
      }
      * {
        box-sizing: border-box;
      }
      html,
      body {
        height: 100%;
        margin: 0;
        overflow: hidden;
      }
      body {
        background: var(--background);
        color: var(--text);
        font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica,
          Arial, sans-serif;
        line-height: 1.45;
      }
      .card {
        display: flex;
        flex-direction: column;
        height: 100%;
        text-decoration: none;
        color: inherit;
      }
      .cover {
        flex: 0 0 118px;
        height: 118px;
        min-height: 0;
        width: 100%;
        object-fit: cover;
        display: block;
        background: var(--surface-muted);
      }
      .content {
        flex: 1 1 auto;
        min-height: 0;
        padding: 0.8rem 1rem 0.9rem;
        display: flex;
        flex-direction: column;
        gap: 0.3rem;
      }
      .kicker {
        margin: 0;
        font-size: 0.68rem;
        letter-spacing: 0.08em;
        text-transform: uppercase;
        color: var(--primary);
        font-weight: 600;
      }
      h1 {
        margin: 0;
        font-size: 1rem;
        line-height: 1.3;
        display: -webkit-box;
        -webkit-line-clamp: 2;
        -webkit-box-orient: vertical;
        overflow: hidden;
      }
      .cta {
        margin-top: auto;
        font-size: 0.78rem;
        font-weight: 600;
        color: var(--primary);
      }
      .card:hover h1 {
        text-decoration: underline;
      }
    </style>
  </head>
  <body>
    <a class="card" href="${esc(canonical)}" target="_blank" rel="noopener noreferrer">
      ${article.cover_image ? `<img class="cover" src="${esc(article.cover_image)}" alt="" />` : ''}
      <div class="content">
        <p class="kicker">${esc(meta)}</p>
        <h1>${esc(article.title)}</h1>
        <span class="cta">Read on dev.to ↗</span>
      </div>
    </a>
  </body>
</html>
`

await mkdir(dirname(outFile), { recursive: true })
await writeFile(outFile, html, 'utf8')

console.log(`wrote ${outFile} from ${canonical}`)
